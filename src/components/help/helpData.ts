export function makeToc(role: 'admin' | 'employee' | 'customer', _blockedIds: string[] = []): HelpTopic[] {
  if (role === 'admin') {
    const mainMenu: HelpTopic = {
      id: 'main-menu',
      title: 'Main Menu',
      summary: 'Complete admin guide with all features and routes.',
      content: [
        'Use the table of contents to navigate quickly.',
        'Previous/Next buttons let you read through in order.',
      ],
    };
    return [mainMenu, ...adminTopics];
  }

  if (role === 'customer') {
    const welcome: HelpTopic = {
      id: 'welcome',
      title: 'Welcome to Prime Auto Detail',
      summary: 'Your guide to using our customer portal.',
      content: [
        'Welcome! This help guide will show you how to use all features of your customer account.',
        'Use the menu above to browse topics, or search for specific information.',
        'We\'re here to make your experience easy and enjoyable!',
      ],
    };
    return [welcome, ...customerTopics];
  }

  // Employees: only show requested items in two sections
  return [...employeeMenuTopics, ...employeeDashboardTopics];
}
